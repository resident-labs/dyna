const workflowHelp = "Start a workflow: a script that fans work out to Pi workers in one box, as a child session. Only the owner or root starts one, and its end reaches the starter as a reply. script is JavaScript that begins with export const meta = {name, profiles, description, size, repo}, a pure literal. args is JSON text, and the script reads it parsed as the global args. Globals: agent(prompt, {profile, schema, label, phase, lane, timeout, worktree}), run(command, {cwd, env, timeout, check, label, phase, lane}), parallel(thunks), pipeline(items, ...stages), merge(results, {base}), workflow(path, args), post(to, text, data, {lane}), phase(title), status(text) and log(...). post() reaches the crew's parent alone, so to is parent or its name. phase is a step's stage and lane the subject it is about, such as lane: g.id; the run page draws each lane's path through the phases. status(text) sets the run's one-line status under its name on the run page and in the Runs list; it is not a step. resume names an ended run, whose finished steps with unchanged keys return their stored results; reload changes a running one. The dyna-workflows skill gives every call's return and failure, resume, worktrees and what a worker knows."

const workflowReloadHelp = "Give a running workflow run a new script. Only the owner or root reloads one. The crew stops the old script and runs the new one in the same box, on the same branches and journal: a call whose step key finished returns its stored result, one whose step is still running waits for that step's worker, and a new key starts. Running steps the new script does not call run on until the run ends. meta must keep the run's name, repo and size; profiles and description may change. Reload is for a live run; resume, on run, starts a new run from an ended one."

var methodRows = buildMethodRows(methodTable)

func buildMethodRows(rows []MethodEntry) map[contract.Method]MethodEntry {
	result := make(map[contract.Method]MethodEntry, len(rows))
	for _, row := range rows {
		result[row.Method] = row
	}
	return result
}

// Methods returns the one method table: exactly one row per Method constant,
// in method order. Rows without actions are engine-only or not yet served.
// Callers must not modify the table.
func Methods() []MethodEntry { return methodTable }
