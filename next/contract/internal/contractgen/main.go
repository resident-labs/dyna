// Command contractgen generates the wire codecs and TypeScript contract.
package contractgen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type body struct{ name, kind string }

func Generate(dir, output string) error {
	fset := token.NewFileSet()
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return err
	}
	var decls []ast.Decl
	var bodies, ops, messages []body
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") || filepath.Base(path) == "union_gen.go" {
			continue
		}
		f, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return err
		}
		decls = append(decls, f.Decls...)
		for _, d := range f.Decls {
			fn, ok := d.(*ast.FuncDecl)
			if !ok || fn.Recv == nil || fn.Name.Name != "EventType" && fn.Name.Name != "OpKind" && fn.Name.Name != "BoxMessageType" {
				continue
			}
			recv, ok := fn.Recv.List[0].Type.(*ast.Ident)
			if !ok {
				return fmt.Errorf("event receiver must be a value")
			}
			if len(fn.Body.List) != 1 {
				return fmt.Errorf("invalid EventType for %s", recv.Name)
			}
			ret, ok := fn.Body.List[0].(*ast.ReturnStmt)
			if !ok || len(ret.Results) != 1 {
				return fmt.Errorf("invalid EventType for %s", recv.Name)
			}
			lit, ok := ret.Results[0].(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				return fmt.Errorf("event type must be literal")
			}
			kind, err := strconv.Unquote(lit.Value)
			if err != nil {
				return err
			}
			if fn.Name.Name == "EventType" {
				bodies = append(bodies, body{recv.Name, kind})
			} else if fn.Name.Name == "OpKind" {
				ops = append(ops, body{recv.Name, kind})
			} else {
				messages = append(messages, body{recv.Name, kind})
			}
		}
	}
	sort.Slice(bodies, func(i, j int) bool { return bodies[i].kind < bodies[j].kind })
	for i, b := range bodies {
		if i > 0 && bodies[i-1].kind == b.kind {
			return fmt.Errorf("duplicate event type %s", b.kind)
		}
	}
	sort.Slice(ops, func(i, j int) bool { return ops[i].kind < ops[j].kind })
	for i, b := range ops {
		if i > 0 && ops[i-1].kind == b.kind {
			return fmt.Errorf("duplicate operation kind %s", b.kind)
		}
	}
	sort.Slice(messages, func(i, j int) bool { return messages[i].kind < messages[j].kind })
	for i, b := range messages {
		if i > 0 && messages[i-1].kind == b.kind {
			return fmt.Errorf("duplicate box message type %s", b.kind)
		}
	}
	var methodValues []string
	for _, d := range decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		for _, sp := range gd.Specs {
			v := sp.(*ast.ValueSpec)
			id, ok := v.Type.(*ast.Ident)
			if !ok || id.Name != "Method" {
				continue
			}
			for _, value := range v.Values {
				if lit, ok := value.(*ast.BasicLit); ok && lit.Kind == token.STRING {
					methodValues = append(methodValues, lit.Value)
				}
			}
		}
	}
	sort.Slice(methodValues, func(i, j int) bool { return methodValues[i] < methodValues[j] })
	for i := 1; i < len(methodValues); i++ {
		if methodValues[i] == methodValues[i-1] {
			return fmt.Errorf("duplicate method %s", methodValues[i])
		}
	}
	var g bytes.Buffer
	g.WriteString(`// Code generated by contractgen; DO NOT EDIT.
package contract
import ("bytes"; "encoding/json"; "fmt")
func (e Event) MarshalJSON() ([]byte, error) {
 if e.Body == nil { return nil, fmt.Errorf("event body is nil") }
 type wire struct { Seq int64 @json:"seq"@; ID EventID @json:"id"@; Time time.Time @json:"at"@; Room RoomID @json:"room,omitempty"@; From Principal @json:"from"@; Type EventType @json:"type"@; Body EventBody @json:"body"@ }
 return json.Marshal(wire{e.Seq,e.ID,e.Time,e.Room,e.From,e.Body.EventType(),e.Body})
}
func (e *Event) UnmarshalJSON(data []byte) error {
 var w struct { Seq int64 @json:"seq"@; ID EventID @json:"id"@; Time time.Time @json:"at"@; Room RoomID @json:"room,omitempty"@; From Principal @json:"from"@; Type EventType @json:"type"@; Body json.RawMessage @json:"body"@ }
 if err := json.Unmarshal(data,&w); err != nil { return err }
 b, err := decodeEventBody(w.Type,w.Body); if err != nil { return err }
 *e = Event{Seq:w.Seq, ID:w.ID, Time:w.Time, Room:w.Room, From:w.From, Body:b}; return nil
}
func decodeEventBody(t EventType, data json.RawMessage) (EventBody,error) {
 switch t {
`)
	for _, b := range bodies {
		fmt.Fprintf(&g, "case %q: var v %s; if err := json.Unmarshal(data,&v); err != nil { return nil,err }; return v,nil\n", b.kind, b.name)
	}
	g.WriteString(`default: return nil,fmt.Errorf("unknown event type %q",t)
 }
}
func (o Operation) MarshalJSON() ([]byte,error) {
 if o.Args != nil && o.Args.OpKind() != o.Kind { return nil,fmt.Errorf("operation kind does not match arguments") }
 type plain Operation
 return json.Marshal(plain(o))
}
func (o *Operation) UnmarshalJSON(data []byte) error {
 type plain Operation
 var w struct { *plain; Args json.RawMessage @json:"args"@ }
 var p plain; w.plain = &p
 dec := json.NewDecoder(bytes.NewReader(data)); dec.DisallowUnknownFields(); if err := dec.Decode(&w); err != nil { return err }
 args, err := decodeOpArgs(p.Kind,w.Args); if err != nil { return err }; p.Args=args; *o=Operation(p); return nil
}
func decodeOpArgs(k OpKind, data json.RawMessage) (OpArgs,error) {
 switch k {
`)
	for _, b := range ops {
		fmt.Fprintf(&g, "case %q: var v %s; dec := json.NewDecoder(bytes.NewReader(data)); dec.DisallowUnknownFields(); if err := dec.Decode(&v); err != nil { return nil,err }; return v,nil\n", b.kind, b.name)
	}
	g.WriteString(`default: return nil,fmt.Errorf("unknown operation kind %q",k)
 }
}
`)
	g.WriteString("\nvar eventBodyTypes = []EventType{")
	for _, b := range bodies {
		fmt.Fprintf(&g, "%q,", b.kind)
	}
	g.WriteString("}\n")
	g.WriteString(`
func (m BoxMessage) MarshalJSON() ([]byte,error) {
 if m.Body == nil { return nil,fmt.Errorf("box message body is nil") }
 return json.Marshal(struct { Type BoxMessageType @json:"type"@; Body BoxMessageBody @json:"body"@ }{m.Body.BoxMessageType(),m.Body})
}
func (m *BoxMessage) UnmarshalJSON(data []byte) error {
 var w struct { Type BoxMessageType @json:"type"@; Body json.RawMessage @json:"body"@ }
 if err := json.Unmarshal(data,&w); err != nil {return err}
 switch w.Type {
`)
	for _, b := range messages {
		fmt.Fprintf(&g, "case %q: var v %s; if err := json.Unmarshal(w.Body,&v); err != nil { return err }; m.Body = v; return nil\n", b.kind, b.name)
	}
	g.WriteString(`default: return fmt.Errorf("%w %q",ErrUnknownBoxMessage,w.Type)
 }
}
`)
	g.WriteString("\nvar boxMessageTypes = []BoxMessageType{")
	for _, b := range messages {
		fmt.Fprintf(&g, "%q,", b.kind)
	}
	g.WriteString("}\n")
	g.WriteString("\n// AllOpKinds lists every operation kind.\nvar AllOpKinds = []OpKind{")
	for _, b := range ops {
		fmt.Fprintf(&g, "%q,", b.kind)
	}
	g.WriteString("}\n")
	g.WriteString("\n// AllMethods lists every Method constant.\nvar AllMethods = []Method{")
	for _, m := range methodValues {
		fmt.Fprintf(&g, "%s,", m)
	}
	g.WriteString("}\n")
	source := strings.ReplaceAll(g.String(), "@", "`")
	source = strings.Replace(source, `"fmt")`, `"fmt"; "time")`, 1)
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(output, "union_gen.go"), formatted, 0644); err != nil {
		return err
	}
	enums := map[string][]string{}
	for _, d := range decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		for _, sp := range gd.Specs {
			v := sp.(*ast.ValueSpec)
			id, ok := v.Type.(*ast.Ident)
			if !ok {
				continue
			}
			for _, value := range v.Values {
				lit, ok := value.(*ast.BasicLit)
				if ok && lit.Kind == token.STRING {
					enums[id.Name] = append(enums[id.Name], lit.Value)
				}
			}
		}
	}
	var ts bytes.Buffer
	ts.WriteString("// Code generated by contractgen; DO NOT EDIT.\n")
	for _, d := range decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, sp := range gd.Specs {
			t := sp.(*ast.TypeSpec)
			if !ast.IsExported(t.Name.Name) {
				continue
			}
			if t.Name.Name == "EventBody" || t.Name.Name == "OpArgs" || t.Name.Name == "BoxMessageBody" {
				continue
			}
			if t.Name.Name == "BoxMessage" {
				ts.WriteString("export type BoxMessage = BoxMessageBody;\n")
				continue
			}
			if t.Name.Name == "Event" {
				ts.WriteString("export type Event = { seq: number; id: EventID; at: string; room?: RoomID; from: Principal } & EventBody;\n")
				continue
			}
			if values := enums[t.Name.Name]; len(values) > 0 && t.Name.Name != "EventType" && t.Name.Name != "OpKind" && t.Name.Name != "HostName" && t.Name.Name != "AccountProvider" && t.Name.Name != "ModelProvider" {
				fmt.Fprintf(&ts, "export type %s = %s;\n", t.Name.Name, strings.Join(values, " | "))
				continue
			}
			fmt.Fprintf(&ts, "export type %s = %s;\n", t.Name.Name, tsType(t.Type))
		}
	}
	ts.WriteString("export type EventBody =\n")
	for _, b := range bodies {
		fmt.Fprintf(&ts, "  | { type: %q; body: %s }\n", b.kind, b.name)
	}
	ts.WriteString(";\nexport type OpArgs = ")
	if len(ops) == 0 {
		ts.WriteString("never")
	} else {
		for i, b := range ops {
			if i > 0 {
				ts.WriteString(" | ")
			}
			ts.WriteString(b.name)
		}
	}
	ts.WriteString(";\nexport type BoxMessageBody =\n")
	for _, b := range messages {
		fmt.Fprintf(&ts, "  | { type: %q; body: %s }\n", b.kind, b.name)
	}
	ts.WriteString(";\n")
	ts.WriteString("export interface MethodMap {\n")
	for _, d := range decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		for _, sp := range gd.Specs {
			v := sp.(*ast.ValueSpec)
			id, ok := v.Type.(*ast.Ident)
			if !ok || id.Name != "Method" {
				continue
			}
			for i, n := range v.Names {
				if i >= len(v.Values) {
					continue
				}
				lit, ok := v.Values[i].(*ast.BasicLit)
				if !ok {
					continue
				}
				name := strings.TrimPrefix(n.Name, "Method")
				fmt.Fprintf(&ts, "  %s: { request: %sRequest; response: %sResponse };\n", lit.Value, name, name)
			}
		}
	}
	ts.WriteString("}\n")
	if err := os.MkdirAll(filepath.Join(output, "../web/src/lib"), 0755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(output, "../web/src/lib/contract.gen.ts"), ts.Bytes(), 0644)
}
func tsType(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return "string"
		case "bool":
			return "boolean"
		case "int", "int64", "int32", "uint", "uint64", "float32", "float64":
			return "number"
		case "byte":
			return "number"
		}
		return t.Name
	case *ast.SelectorExpr:
		if x, ok := t.X.(*ast.Ident); ok && x.Name == "time" && t.Sel.Name == "Time" {
			return "string"
		}
	case *ast.StarExpr:
		return tsType(t.X) + " | null"
	case *ast.ArrayType:
		if id, ok := t.Elt.(*ast.Ident); ok && id.Name == "byte" {
			return "string | null"
		}
		return "Array<" + tsType(t.Elt) + "> | null"
	case *ast.MapType:
		return "Record<" + tsType(t.Key) + ", " + tsType(t.Value) + "> | null"
	case *ast.StructType:
		var b strings.Builder
		b.WriteString("{")
		for _, f := range t.Fields.List {
			if len(f.Names) == 0 || f.Tag == nil {
				continue
			}
			tag, _ := strconv.Unquote(f.Tag.Value)
			parts := strings.Split(strings.TrimPrefix(tag, "json:\""), "\",")
			raw := strings.TrimSuffix(parts[0], "\"")
			name := strings.Split(raw, ",")[0]
			optional := strings.Contains(tag, "omitempty") || strings.Contains(tag, "omitzero")
			fmt.Fprintf(&b, " %s", name)
			if optional {
				b.WriteString("?")
			}
			fmt.Fprintf(&b, ": %s;", tsType(f.Type))
		}
		b.WriteString(" }")
		return b.String()
	}
	panic(fmt.Sprintf("unsupported type %T", e))
}
