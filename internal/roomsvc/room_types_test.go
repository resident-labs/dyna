package roomsvc

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"reflect"
	"slices"
	"strings"
	"testing"
	"time"
)

// roomTypesFile is the TypeScript the web app imports for the room API. It is
// generated from the Go structs, so a field cannot drift from its web copy.
// Regenerate it with DYNA_UPDATE_ROOM_TYPES=1 go test ./internal/roomsvc/ -run RoomTypes.
const roomTypesFile = "../../web/src/lib/api/room.gen.ts"

// roomTypesSource is the Go file that declares roomWireTypes. Its doc
// comments become the TypeScript comments, which reflection cannot read.
const roomTypesSource = "roomsvc.go"

// roomWireTypes are the roomsvc structs the web copies, in the order the
// generated file writes them.
var roomWireTypes = []reflect.Type{reflect.TypeFor[Room](), reflect.TypeFor[RoomLimits]()}

func TestRoomTypesFileMatchesGo(t *testing.T) {
	want, err := generateRoomTypes()
	if err != nil {
		t.Fatal(err)
	}
	if os.Getenv("DYNA_UPDATE_ROOM_TYPES") != "" {
		if err := os.WriteFile(roomTypesFile, want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(roomTypesFile)
	if err != nil || !bytes.Equal(got, want) {
		t.Fatalf("%s is out of date with roomsvc.Room; run DYNA_UPDATE_ROOM_TYPES=1 go test ./internal/roomsvc/ -run RoomTypes (read error: %v)", roomTypesFile, err)
	}
}

func generateRoomTypes() ([]byte, error) {
	file, err := parser.ParseFile(token.NewFileSet(), roomTypesSource, nil, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	var b strings.Builder
	b.WriteString("// Code generated by internal/roomsvc/room_types_test.go from internal/roomsvc/roomsvc.go. DO NOT EDIT.\n")
	b.WriteString("// Regenerate it with DYNA_UPDATE_ROOM_TYPES=1 go test ./internal/roomsvc/ -run RoomTypes.\n\n")
	for _, typ := range roomWireTypes {
		typeDoc, fieldDocs := goDocs(file, typ.Name())
		writeTSComment(&b, "", typeDoc)
		fmt.Fprintf(&b, "export interface %s {\n", typ.Name())
		for i := range typ.NumField() {
			field := typ.Field(i)
			name, options, _ := strings.Cut(field.Tag.Get("json"), ",")
			if !field.IsExported() || name == "" || name == "-" {
				continue
			}
			tsType, err := tsWireType(field.Type)
			if err != nil {
				return nil, fmt.Errorf("%s.%s: %w", typ.Name(), field.Name, err)
			}
			optional := ""
			if strings.Contains(options, "omitempty") {
				optional = "?"
			}
			writeTSComment(&b, "  ", fieldDocs[field.Name])
			fmt.Fprintf(&b, "  %s%s: %s\n", name, optional, tsType)
		}
		b.WriteString("}\n\n")
	}
	return []byte(strings.TrimRight(b.String(), "\n") + "\n"), nil
}

// goDocs returns the doc comment of the named struct and of each of its
// fields, read from the parsed Go file.
func goDocs(file *ast.File, name string) (string, map[string]string) {
	fields := map[string]string{}
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok || gen.Tok != token.TYPE {
			continue
		}
		for _, spec := range gen.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok || typeSpec.Name.Name != name {
				continue
			}
			st, ok := typeSpec.Type.(*ast.StructType)
			if !ok {
				continue
			}
			for _, f := range st.Fields.List {
				for _, n := range f.Names {
					fields[n.Name] = f.Doc.Text()
				}
			}
			doc := typeSpec.Doc
			if doc == nil {
				doc = gen.Doc
			}
			return doc.Text(), fields
		}
	}
	return "", fields
}

// writeTSComment writes a Go doc comment as TypeScript line comments.
func writeTSComment(b *strings.Builder, indent, doc string) {
	if doc == "" {
		return
	}
	for _, line := range strings.Split(strings.TrimSpace(doc), "\n") {
		if line == "" {
			fmt.Fprintf(b, "%s//\n", indent)
			continue
		}
		fmt.Fprintf(b, "%s// %s\n", indent, line)
	}
}

// tsWireType maps a field type of the wire structs to TypeScript. encoding/json
// writes a time.Time as RFC 3339 text, so it reads as a string.
func tsWireType(typ reflect.Type) (string, error) {
	if typ == reflect.TypeFor[time.Time]() {
		return "string", nil
	}
	switch typ.Kind() {
	case reflect.String:
		return "string", nil
	case reflect.Int, reflect.Int64:
		return "number", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Struct:
		if !slices.Contains(roomWireTypes, typ) {
			return "", fmt.Errorf("struct %s is not in roomWireTypes", typ.Name())
		}
		return typ.Name(), nil
	}
	return "", fmt.Errorf("unsupported type %s", typ)
}
