package roomsvc

import (
	"bytes"
	"fmt"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/gzuidhof/tygo/config"
	"github.com/gzuidhof/tygo/tygo"
)

const (
	sessionTypesConfig = "../../tygo.yaml"
	sessionTypesFile   = "../../web/src/lib/api/session.gen.ts"
)

// TestSessionTypesFileMatchesGo keeps the web session contract on its Go
// source of truth. Regenerate it with:
// DYNA_UPDATE_SESSION_TYPES=1 go test ./internal/roomsvc/ -run SessionTypes.
func TestSessionTypesFileMatchesGo(t *testing.T) {
	want, err := generateTypes("web/src/lib/api/session.gen.ts", "DYNA_UPDATE_SESSION_TYPES=1 go test ./internal/roomsvc/ -run SessionTypes")
	if err != nil {
		t.Fatal(err)
	}
	if os.Getenv("DYNA_UPDATE_SESSION_TYPES") != "" {
		if err := os.WriteFile(sessionTypesFile, want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(sessionTypesFile)
	if err != nil || !bytes.Equal(got, want) {
		t.Fatalf("%s is out of date; run DYNA_UPDATE_SESSION_TYPES=1 go test ./internal/roomsvc/ -run SessionTypes (read error: %v)", sessionTypesFile, err)
	}
}

// generateSessionTypes calls tygo's in-memory library for each contract-only
// file. Their package entries share one output because the web API is one module.
func generateTypes(output, update string) ([]byte, error) {
	conf := config.ReadFromFilepath(sessionTypesConfig)
	if len(conf.Packages) == 0 {
		return nil, fmt.Errorf("%s has no packages", sessionTypesConfig)
	}
	var b strings.Builder
	b.WriteString("// Code generated by tygo. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Regenerate with %s.\n", update)
	found := false
	for _, pkg := range conf.Packages {
		if pkg.OutputPath != output {
			continue
		}
		if !found {
			b.WriteString(pkg.Frontmatter)
			found = true
		}
		pkgConfig := *pkg
		pkgConfig.TypeMappings = make(map[string]string, len(conf.TypeMappings)+len(pkg.TypeMappings))
		for name, tsType := range conf.TypeMappings {
			pkgConfig.TypeMappings[name] = tsType
		}
		for name, tsType := range pkg.TypeMappings {
			pkgConfig.TypeMappings[name] = tsType
		}
		packageDir := strings.TrimPrefix(pkg.Path, "dyna-agent/")
		if packageDir == pkg.Path {
			return nil, fmt.Errorf("%s is outside dyna-agent", pkg.Path)
		}
		for _, name := range pkg.IncludeFiles {
			if filepath.Base(name) != name {
				return nil, fmt.Errorf("%s include %q is not a base name", pkg.Path, name)
			}
			filename := filepath.Join("../..", packageDir, name)
			source, err := os.ReadFile(filename)
			if err != nil {
				return nil, err
			}
			file, err := parser.ParseFile(token.NewFileSet(), filename, source, parser.ParseComments)
			if err != nil {
				return nil, err
			}
			// ConvertGoToTypescript supplies its own package clause. Keep the
			// imports and declarations from the configured source file.
			body := source[int(file.Name.End())-1:]
			code, err := tygo.ConvertGoToTypescript(string(body), pkgConfig)
			if err != nil {
				return nil, fmt.Errorf("generate %s: %w", filename, err)
			}
			fmt.Fprintf(&b, "\n//////////\n// source: %s\n\n", filepath.Join(packageDir, name))
			b.WriteString(code)
		}
	}
	if !found {
		return nil, fmt.Errorf("no packages output %s", output)
	}
	return []byte(b.String()), nil
}
